-- Pure Lua 5.1 tests; no game client or UI is required.
local CG = {}
assert(loadfile("addon/Pricing.lua"))("CoinGuardian", CG)
local P = CG.Pricing
local function equal(actual, expected, message)
    assert(actual == expected, (message or "Mismatch") .. ": " .. tostring(actual) .. " != " .. tostring(expected))
end

local r = P.Evaluate(10000, 1, 20000, 50, 600)
equal(r.state, "sell")
equal(r.vendor, 10000)
equal(r.gross, 20000)
equal(r.cut, 1000)
equal(r.net, 19000)
equal(r.profit, 9000)
equal(r.profitPercent, 90)
equal(r.deposit, 600)
r = P.Evaluate(10000, 1, 20000, 100)
equal(r.state, "below_target")
r = P.Evaluate(10000, 1, 9000, 0)
equal(r.state, "loss")
equal(r.cut, 450)
equal(r.net, 8550)
r = P.Evaluate(10000, 1, 10000, 0)
equal(r.state, "loss", "5% fee turns parity price into a loss")
r = P.Evaluate(10000, 1, 15000, 50)
equal(r.state, "below_target", "threshold is computed on post-cut proceeds")
r = P.Evaluate(10000, 1, 15790, 50)
equal(r.state, "sell", "threshold after cut")
r = P.Evaluate(100, 7, 200, 50)
equal(r.vendor, 700)
equal(r.gross, 1400)
equal(r.cut, 70)
equal(r.net, 1330)
r = P.Evaluate(nil, 1, 20000, 50)
equal(r.state, "unavailable")
equal(r.net, 19000)
r = P.Evaluate(0, 1, 100, 50)
equal(r.state, "zero_vendor")
equal(r.profitPercent, nil)
r = P.Evaluate(100, 1, nil, 50)
equal(r.state, "unavailable")
r = P.Evaluate(100, 0, 1000, 50)
equal(r.state, "unavailable")
r = P.Evaluate(100, 1, -1, 50)
equal(r.state, "unavailable")
r = P.Evaluate(100, 1, 1, 0)
equal(r.cut, 0, "5% of one copper rounds down")
equal(P.NormalizeMargin(nil), 50)
equal(P.NormalizeMargin(48), 50)
equal(P.NormalizeMargin(74), 75)
equal(P.NormalizeMargin(-12), 0)
equal(P.NormalizeMargin(250), 200)
equal(P.CoinText(19000), "1g 90s 00c")
equal(P.CoinText(-450), "-0g 04s 50c")
print("PASS: Coin Guardian copper math and margin tests")
